// Explicit Fable 5.2 plans use the declared recommendation when effort is absent,
// and preserve an explicit xhigh. Planning checks argv only; no model is executed.
func TestExplicitFable52Plan(t *testing.T) {
	registry := isolatedRegistry(t, nil)
	for _, tc := range []struct{ effort, want string }{{"", "high"}, {"xhigh", "xhigh"}} {
		t.Run(tc.want, func(t *testing.T) {
			plan, err := vendorplugin.BuildLaunch(context.Background(), registry, opusRequest(t, "claude-fable-5-2", tc.effort), agentic.LaunchModeExec)
			if err != nil {
				t.Fatalf("explicit Fable 5.2 plan: %v", err)
			}
			if !museArgvPair(plan.Argv, "--model", "claude-fable-5-2") || !museArgvPair(plan.Argv, "--effort", tc.want) {
				t.Fatalf("expected exact model and effort %s in argv: %v", tc.want, plan.Argv)
			}
		})
	}
}

// The refusal cases return no partial plan; nearby valid plans above prevent
// rejection of every request from satisfying these checks.
func TestFable52RefusesWrongSystemAndEffort(t *testing.T) {
	registry := isolatedRegistry(t, nil)

	for _, tc := range []struct {
		model   vendorplugin.ModelID
		runtime vendorplugin.RuntimeID
		effort  string
		want    error
	}{
		{"claude-fable-5-2", "pi-anthropic", "high", vendorplugin.ErrModelNotDrivenBySystem},
		{"claude-fable-5-2", "claude", "ultra", vendorplugin.ErrEffortNotInVocabulary},
		{"claude-fable-5-1", "claude", "", vendorplugin.ErrEffortMissing},
		{"", "claude", "high", vendorplugin.ErrUnknownModel},
	} {
		req := opusRequest(t, tc.model, tc.effort)
		req.Runtime = tc.runtime
		plan, err := vendorplugin.BuildLaunch(context.Background(), registry, req, agentic.LaunchModeExec)
		if !errors.Is(err, tc.want) || !reflect.DeepEqual(plan, agentic.Plan{}) {
			t.Errorf("%+v: plan=%+v err=%v, want zero plan and %v", tc, plan, err, tc.want)
		}
	}
}

// Captured from clean main 25a9f97d84a6fb709b1c9a34dd623bc31c446751 before
// implementation. Byte comparisons pin every old field, declaration order,
// lineup/default top row, preference order and Tied flag across all vendors
// and the vendor-unresolved runtime. No golden is regenerated by this test.
func TestUnmeasuredPreservesAllExistingRowsAndLineups(t *testing.T) {
	rows := map[string][]vendorplugin.Model{}
	lineups := map[string][]vendorplugin.RankedModel{}
	for _, id := range []vendorplugin.VendorID{"alibaba", "anthropic", "google", "openai"} {
		v, ok := vendorplugin.Default.Lookup(id)
		if !ok {
			t.Fatal(id)
		}
		old := []vendorplugin.Model{}
		for _, m := range v.Models() {
			if m.ID != "claude-fable-5-2" {
				old = append(old, m)
			}
		}
		rows[string(id)] = old
		lineups[string(id)] = vendorplugin.LineupOf(v)
	}
	for _, d := range vendorplugin.Default.RuntimeDeclarations() {
		if d.Vendor != "" {
			continue
		}
		rows["runtime:"+string(d.ID)] = d.Models
		lineups["runtime:"+string(d.ID)] = d.LineupOfDeclaration()
	}
	for name, value := range map[string]any{"rows": rows, "lineups": lineups} {
		got, err := json.Marshal(value)
		if err != nil {
			t.Fatal(err)
		}
		want, err := os.ReadFile("testdata/pre-unmeasured-" + name + ".json")
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s changed from pre-unmeasured main", name)
		}
	}
}

// The compiled row carries availability evidence and a declared vocabulary,
// and exports no rank/score, benchmark result, alias, or recommendation.
func TestFable52HasOnlyAnUnmeasuredClaim(t *testing.T) {
	v, _ := vendorplugin.Default.Lookup("anthropic")
	var row vendorplugin.Model
	for _, m := range v.Models() {
		if m.ID == "claude-fable-5-2" {
			row = m
		}
	}
	if row.ID == "" || row.Rank != nil || row.Unmeasured == nil || row.Unmeasured.Kind != "unmeasured" || row.Unmeasured.AsOf != "2026-11-10" || row.AliasOf != "" || row.Recommended {
		t.Fatalf("bad availability-only row: %+v", row)
	}
	if !strings.Contains(row.Unmeasured.Source, "Curator orchestrator") || !strings.Contains(row.Unmeasured.Observation, "exit 0") {
		t.Fatal("missing attributed availability observation")
	}
	if !reflect.DeepEqual(row.Systems, []agentic.SystemID{"claude-code"}) || row.Effort.Recommended != "high" || !reflect.DeepEqual(row.Effort.Vocabulary, []string{"low", "medium", "high", "xhigh", "max"}) {
		t.Fatalf("changed declaration: %+v", row)
	}
	raw, err := json.Marshal(row)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Contains(raw, []byte(`"Score"`)) || bytes.Contains(raw, []byte(`"Rank"`)) {
		t.Fatalf("unmeasured row exported a score: %s", raw)
	}
	for _, result := range benchdata.BugHuntRows() {
		if result.ModelID == string(row.ID) {
			t.Fatal("availability was exported as benchmark evidence")
		}
	}
}
